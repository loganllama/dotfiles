#!/bin/bash


# "standard" install.sh to replicate what it does when install.sh is not present.
safe_dot_symlinks() {
    # Get the directory in which this script lives.
    script_dir=$(dirname "$(readlink -f "$0")")

    # Get a list of all files in this directory that start with a dot.
    files=$(find -maxdepth 1 -type f -name ".*")

    # Create a symbolic link to each file in the home directory.
    for file in $files; do
        name=$(basename $file)
        echo "Creating symlink to $name in home directory."
        rm -rf ~/$name
        ln -s $script_dir/$name ~/$name
    done
}

safe_config_symlink() {
    # if we proceed with an empty string, then we'd remove ~/.config
    if [ -z "$1" ]; then
        echo "Error: argument is empty." >&2
        return 1
    fi
    script_dir=$(dirname "$(readlink -f "$0")")
    echo "Creating symlink to $1 in ~/.config/..."
    dest="$HOME/.config/$1"
    dest_dir="$(dirname $dest)"
    [ "$dest_dir" != "$HOME/.config" ] && rm -rf "$dest_dir"
    mkdir -p "$dest_dir"
    ln -s "$script_dir/$1" "$dest"
}

safe_obsidian_symlink() {
    if [ -z "$1" ]; then
        echo "Error: argument 1 is empty." >&2
        return 1
    fi
    if [ -z "$2" ]; then
        echo "Error: argument 2 is empty." >&2
        return 1
    fi
    script_dir=$(dirname "$(readlink -f "$0")")
    source_file="$script_dir/$1"
    dest_dir="/workspaces/obsidian"
    dest="$dest_dir/$2"
    echo "Creating symlink to $source_file in $dest"
    ln -s "$source_file" "$dest"
}

# Symlink every script in this repo's bin/ into ~/bin and ensure it is
# executable. ~/bin is already added to PATH by bash_additions.sh.
install_bin_scripts() {
    script_dir=$(dirname "$(readlink -f "$0")")
    local src_dir="$script_dir/bin"
    if [ ! -d "$src_dir" ]; then
        echo "Skipping bin scripts install: $src_dir not found."
        return 0
    fi
    mkdir -p "$HOME/bin"
    for file in "$src_dir"/*; do
        [ -f "$file" ] || continue
        name=$(basename "$file")
        echo "Installing $name into ~/bin..."
        chmod +x "$file"
        rm -rf "$HOME/bin/$name"
        ln -s "$file" "$HOME/bin/$name"
    done
}

# Symlink every skill directory in this repo's claude/skills/ into
# ~/.claude/skills/. Symlinks the directory rather than its contents so
# files added inside a skill need no change here.
install_claude_skills() {
    script_dir=$(dirname "$(readlink -f "$0")")
    local src_dir="$script_dir/claude/skills"
    if [ ! -d "$src_dir" ]; then
        echo "Skipping Claude skills install: $src_dir not found."
        return 0
    fi
    mkdir -p "$HOME/.claude/skills"
    for dir in "$src_dir"/*/; do
        [ -d "$dir" ] || continue
        name=$(basename "$dir")
        local dest="$HOME/.claude/skills/$name"
        # Deliberately not rm -rf: ~/.claude holds live session state, and a
        # non-symlink here is a hand-written skill rather than a stale install.
        # Skip it instead of destroying it, and never touch ~/.claude/skills
        # itself, which would take unmanaged skills with it.
        if [ -e "$dest" ] && [ ! -L "$dest" ]; then
            echo "Skipping skill $name: $dest exists and is not a symlink."
            continue
        fi
        echo "Installing Claude skill $name..."
        rm -f "$dest"
        ln -s "${dir%/}" "$dest"
    done
}

# Generate this dev box's short ID once and keep it across reruns. It
# lives outside ~/.config/jj because safe_config_symlink wipes that dir.
# bash_additions.sh reads it into DEV_INSTANCE_ID and BRANCH_PREFIX.
DEV_INSTANCE_ID_FILE="$HOME/.config/dev-instance/id"
init_dev_instance_id() {
    if [ -s "$DEV_INSTANCE_ID_FILE" ]; then
        echo "Dev instance ID already set: $(cat "$DEV_INSTANCE_ID_FILE")"
        return 0
    fi
    mkdir -p "$(dirname "$DEV_INSTANCE_ID_FILE")"
    tr -dc 'a-z0-9' </dev/urandom | head -c 3 >"$DEV_INSTANCE_ID_FILE"
    echo "Generated dev instance ID: $(cat "$DEV_INSTANCE_ID_FILE")"
}

# Write per-box jj settings to conf.d, which jj loads after config.toml.
# Must run after safe_config_symlink "jj/config.toml", which removes
# ~/.config/jj. Auto-tracks this box's lc/<id>/* bookmarks plus shared
# single-segment lc/<name> ones. jj's glob `*` matches `/`, hence the
# ~glob:"lc/*/*" exclusion that hides other boxes' bookmarks.
write_jj_instance_config() {
    if [ ! -s "$DEV_INSTANCE_ID_FILE" ]; then
        echo "Skipping jj instance config: $DEV_INSTANCE_ID_FILE missing."
        return 0
    fi
    local id
    id="$(cat "$DEV_INSTANCE_ID_FILE")"
    local dest="$HOME/.config/jj/conf.d/instance.toml"
    mkdir -p "$(dirname "$dest")"
    echo "Writing jj instance config for lc/$id/ to $dest..."
    cat >"$dest" <<EOF
# Generated by dotfiles/install.sh for dev instance "$id". Do not edit.
[remotes.origin]
auto-track-bookmarks = 'glob:"lc/$id/*" | (glob:"lc/*" & ~glob:"lc/*/*")'

[templates]
git_push_bookmark = '"lc/$id/push-" ++ change_id.short()'
EOF
}

# Source bash_additions.sh from ~/.bashrc in two places, each added once:
# - the top, for non-interactive shells, which Debian's .bashrc guard
#   would otherwise turn away before they reach the bottom line;
# - the bottom, for interactive shells, keeping it after fzf's rc line
#   and the stock PS1 setup as before.
install_bash_additions_in_bashrc() {
    local top='case $- in *i*) ;; *) [ -f ~/bash_additions.sh ] && . ~/bash_additions.sh ;; esac'
    local bottom='[ -f ~/bash_additions.sh ] && . ~/bash_additions.sh'
    touch ~/.bashrc
    if ! grep -qxF "$top" ~/.bashrc; then
        echo "Adding non-interactive bash_additions source to top of ~/.bashrc..."
        if [ -s ~/.bashrc ]; then
            sed -i "1i $top" ~/.bashrc
        else
            echo "$top" >~/.bashrc
        fi
    fi
    if ! grep -qxF "$bottom" ~/.bashrc; then
        echo "Adding interactive bash_additions source to end of ~/.bashrc..."
        echo "$bottom" >>~/.bashrc
    fi
}

# Write the gws OAuth client file from GWS_CLIENT_SECRET, which the devbox
# setup provides, so the secret stays out of this public repo. Rewritten on
# every run so a rotated secret takes effect. The client ID isn't secret.
# GOOGLE_WORKSPACE_PROJECT_ID is exported in bash_additions.sh.
write_gws_client_secret() {
    local dest="$HOME/.config/gws/client_secret.json"
    if [ -z "$GWS_CLIENT_SECRET" ]; then
        if [ -s "$dest" ]; then
            echo "GWS_CLIENT_SECRET not set; keeping existing $dest."
        else
            echo "Note: GWS_CLIENT_SECRET is not set, so $dest was not created."
            echo "      Set it in the devbox setup, or add the file by hand, then run 'gws auth login --readonly'."
            echo "      Setup instructions: https://app.getguru.com/card/iGokqkBT/CLI-Tools-for-Agents#QjekaNzRZuD9"
        fi
        return 0
    fi
    echo "Writing $dest from GWS_CLIENT_SECRET..."
    mkdir -p "$(dirname "$dest")"
    (
        umask 077
        cat >"$dest" <<JSON
{
  "installed": {
    "client_id": "841275341868-64agsblb2oce0rvf6uih75eahlma5hlp.apps.googleusercontent.com",
    "project_id": "gws-cli-oauth-496100",
    "auth_uri": "https://accounts.google.com/o/oauth2/auth",
    "token_uri": "https://oauth2.googleapis.com/token",
    "auth_provider_x509_cert_url": "https://www.googleapis.com/oauth2/v1/certs",
    "client_secret": "$GWS_CLIENT_SECRET",
    "redirect_uris": [
      "http://localhost"
    ]
  }
}
JSON
    )
    chmod 600 "$dest"
}

safe_home_symlink() {
    # if we proceed with an empty string, then we'd remove ~/
    if [ -z "$1" ]; then
        echo "Error: argument is empty." >&2
        return 1
    fi
    script_dir=$(dirname "$(readlink -f "$0")")
    echo "Creating symlink to $1 in home directory."
    rm -rf "$HOME/$1"
    ln -s "$script_dir/$1" "$HOME/$1"
}

# Set up jj in the obsidian checkout and provision the agent workspace
# pool (ws1..ws5, each parked on the `parking_lot` bookmark, plus the lease
# dir) via `ws init`. Idempotent: every step skips what already exists.
init_agent_jj_workspaces() {
    local obsidian_dir="/workspaces/obsidian"

    if [ ! -d "$obsidian_dir" ]; then
        echo "Skipping jj workspace init: $obsidian_dir not found."
        return 0
    fi
    if ! command -v jj >/dev/null 2>&1; then
        echo "Skipping jj workspace init: jj not on PATH."
        return 0
    fi

    # Colocate jj with the existing git clone if not already done.
    if [ ! -d "$obsidian_dir/.jj" ]; then
        echo "Initializing jj (colocated) in $obsidian_dir..."
        (cd "$obsidian_dir" && jj git init --colocate) || {
            echo "jj git init failed; skipping workspace setup."
            return 0
        }
    fi

    # Track main against origin and align local main with main@origin so
    # subsequent operations (parking_lot creation, workspace placement,
    # and `jj sync`) are based on the upstream tip.
    (cd "$obsidian_dir" && jj bookmark track main --remote=origin) \
        || echo "Note: 'jj bookmark track main' skipped or already tracked."
    (cd "$obsidian_dir" && jj bookmark set main -r main@origin --allow-backwards) \
        || echo "Note: 'jj bookmark set main' skipped or already aligned."

    # The pool itself (parking_lot, ws1..ws5, .leases/) is owned by `ws`,
    # so the pool list lives in one place (ws/lib/config.sh). Called by its
    # dotfiles path rather than ~/bin/ws so it doesn't depend on PATH.
    script_dir=$(dirname "$(readlink -f "$0")")
    "$script_dir/bin/ws" init \
        || echo "Note: 'ws init' reported problems; see above. Re-run it after fixing them."

    # Rebase the user's mutable stacks onto main. Conflicts here are
    # normal and expected — the user resolves them as part of normal
    # work. (`jj sync` is an alias defined in jj/config.toml.)
    echo "Running 'jj sync' in $obsidian_dir..."
    (cd "$obsidian_dir" && jj sync) \
        || echo "Note: 'jj sync' reported issues (likely conflicts to resolve later)."
}

safe_dot_symlinks

init_dev_instance_id

safe_config_symlink "jj/config.toml"
write_jj_instance_config
safe_config_symlink "starship.toml"

safe_obsidian_symlink CLAUDE.local.md CLAUDE.local.md
safe_obsidian_symlink loganllama_pr_style_guide.local.md loganllama_pr_style_guide.local.md
safe_obsidian_symlink settings.local.json .claude/settings.local.json

safe_home_symlink "bash_additions.sh"
[ -f ~/bash_additions.sh ] && . ~/bash_additions.sh

install_bin_scripts

# we do this before adding the bash_additions source to bashrc because fzf adds its own source to .bashrc
# which needs to happen before the bash_additions source so fzf will be in the path
# the above source was safe because we're not in an interactive session
# ... honestly we could probably omit the source in bash_additions now but meh
echo "Updating fzf..."
sudo apt remove -y fzf
git clone --depth 1 https://github.com/junegunn/fzf.git ~/.fzf
~/.fzf/install --xdg --key-bindings --completion --update-rc

echo "Installing ~/bash_additions.sh..."
install_bash_additions_in_bashrc

echo "Installing Claude..."
curl -fsSL https://claude.ai/install.sh | bash

install_claude_skills

echo "Installing Starship..."
curl -sS https://starship.rs/install.sh | sh -s -- --yes

# The devcontainer image ships rustup in ~/.cargo, with the default
# toolchain pinned to obsidian's rust-toolchain.toml. Leave that default
# alone: obsidian's Rust builds depend on it.

# jj comes from the prebuilt release binary, not `cargo install`. New jj
# releases often raise their MSRV past the image's pinned rustc, and
# compiling jj from source takes minutes anyway.
JJ_VERSION="0.46.0"
echo "Installing Jujutsu v$JJ_VERSION..."
mkdir -p ~/bin
jj_tmp="$(mktemp -d)"
curl -fsSL "https://github.com/jj-vcs/jj/releases/download/v$JJ_VERSION/jj-v$JJ_VERSION-x86_64-unknown-linux-musl.tar.gz" \
    | tar xz -C "$jj_tmp" ./jj \
    && mv "$jj_tmp/jj" ~/bin/jj
rm -rf "$jj_tmp"
# bash_additions' pathadd skips directories that don't exist yet, so
# ~/bin may have been skipped when it was sourced above.
pathadd "$HOME/bin"
jj --version || echo "Warning: jj install failed."

# starship-jj has no prebuilt Linux binary, so build it with the image's
# toolchain.
echo "Installing starship-jj..."
cargo install --locked starship-jj

# jj is now on PATH; provision the agent-team workspaces.
init_agent_jj_workspaces

echo "Installing DD Pup..."
pup_tmp="$(mktemp -d)"
curl -L https://github.com/DataDog/pup/releases/download/v0.60.0/pup_0.60.0_Linux_x86_64.tar.gz | tar xz -C "$pup_tmp" && mkdir -p ~/bin && mv "$pup_tmp/pup" ~/bin/pup
rm -rf "$pup_tmp"

echo "Installing capn..."
npm install -g capn-hook@0.2.2

echo "Installing Google Workspace CLI (gws)..."
npm install -g @googleworkspace/cli
write_gws_client_secret
